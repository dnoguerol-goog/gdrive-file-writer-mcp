"""Model Context Protocol (MCP) server for Google Shared Drive file writing.

Configured specifically for headless Gemini Enterprise Workflow Builder integration
running privately on Google Cloud Run via StreamableHTTP transport.
"""

import asyncio
import logging
from typing import Literal

from mcp.server.fastmcp import FastMCP
from mcp.types import ToolAnnotations
from starlette.applications import Starlette
from starlette.requests import Request
from starlette.responses import JSONResponse

from app.config import Settings, get_settings
from app.drive_client import DriveClient, SaveDriveFileResult

# Initialize logger
settings = get_settings()
logging.basicConfig(
    level=getattr(logging, settings.log_level.upper(), logging.INFO),
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("gdrive-file-mcp")

# Drive client instance management (injectable for testing)
_drive_client: DriveClient | None = None


def get_drive_client() -> DriveClient:
    """Retrieve or initialize the DriveClient."""
    global _drive_client
    if _drive_client is None:
        _drive_client = DriveClient(settings=get_settings())
    return _drive_client


def set_drive_client(client: DriveClient | None) -> None:
    """Set the DriveClient instance (used for testing and dependency injection)."""
    global _drive_client
    _drive_client = client


def create_mcp_server(server_settings: Settings | None = None) -> FastMCP:
    """Factory function to instantiate FastMCP server with all routes and tools."""
    current_settings = server_settings or get_settings()

    # Initialize FastMCP server
    # CRITICAL FastMCP architecture constraints:
    # 1. host="0.0.0.0": Disables localhost-only DNS rebinding protection which otherwise
    #    rejects Cloud Run requests with '421 Misdirected Request' for *.run.app Host headers.
    # 2. stateless_http=True: Required for stateless Cloud Run autoscaling.
    # 3. json_response=True: Ensures JSON responses for StreamableHTTP endpoints.
    # 4. streamable_http_path="/mcp": Mounted at /mcp for Gemini Enterprise custom MCP datastores.
    server = FastMCP(
        name="gdrive-file-mcp",
        host="0.0.0.0",
        port=current_settings.port,
        stateless_http=True,
        json_response=True,
        streamable_http_path="/mcp",
    )

    # Health check endpoint for Cloud Run and container probes
    @server.custom_route("/healthz", methods=["GET"])
    async def health_check(request: Request) -> JSONResponse:
        """Lightweight health check endpoint for Cloud Run container probes."""
        return JSONResponse(
            {
                "status": "healthy",
                "service": "gdrive-file-mcp",
                "transport": "StreamableHTTP",
                "path": "/mcp",
            }
        )

    # Primary file saving tool
    @server.tool(
        name="save_drive_file",
        title="Save file to Google Drive",
        description=(
            "Save generated file to an approved Google Shared Drive folder. "
            "Supports txt, md, csv, json, and native Google Doc conversion. "
            "Configured for headless execution in Gemini Enterprise workflows."
        ),
        annotations=ToolAnnotations(
            title="Save file to Google Drive",
            readOnlyHint=True,
            destructiveHint=False,
            idempotentHint=False,
            openWorldHint=False,
        ),
    )
    async def save_drive_file(
        file_name: str,
        content: str,
        output_format: Literal["txt", "md", "csv", "json", "google_doc"] = "txt",
        folder_alias: str | None = None,
        on_conflict: Literal["create_new", "overwrite"] = "create_new",
    ) -> SaveDriveFileResult:
        """Save file to a Google Shared Drive folder.

        Parameters:
        - file_name: Desired name of the file (e.g. '2026-11-monthly-report.txt'). Path separators and traversal sequences are automatically sanitized.
        - content: UTF-8 text, markdown, CSV, or JSON content generated by upstream workflow steps.
        - output_format: 'txt', 'md', 'csv', 'json' for raw files, or 'google_doc' to convert into a native Google Doc.
        - folder_alias: Optional alias mapped in ALLOWED_SUBFOLDER_MAP (e.g. 'monthly', 'finance'). If omitted, writes to the primary DRIVE_FOLDER_ID.
        - on_conflict: 'create_new' creates a new file; 'overwrite' updates the media of an existing file with the exact same name if found in the target folder.
        """
        logger.info(
            "Tool invocation save_drive_file: file_name=%s, format=%s, alias=%s, on_conflict=%s",
            file_name,
            output_format,
            folder_alias,
            on_conflict,
        )
        client = get_drive_client()

        # Run blocking Drive API I/O in worker thread to prevent event loop blocking
        result = await asyncio.to_thread(
            client.save_file,
            file_name=file_name,
            content=content,
            output_format=output_format,
            folder_alias=folder_alias,
            on_conflict=on_conflict,
        )
        return result

    return server


def create_app(server_settings: Settings | None = None) -> Starlette:
    """Create and return the Starlette ASGI application for FastMCP."""
    server = create_mcp_server(server_settings)
    return server.streamable_http_app()


# Default server and app instances exported for Uvicorn
mcp = create_mcp_server()
app = mcp.streamable_http_app()


def main() -> None:
    """Server entrypoint for direct CLI invocation."""
    import uvicorn

    current_settings = get_settings()
    logger.info("Starting gdrive-file-mcp server on 0.0.0.0:%s", current_settings.port)
    uvicorn.run(
        "app.server:app",
        host="0.0.0.0",
        port=current_settings.port,
        log_level=current_settings.log_level.lower(),
        access_log=True,
    )


if __name__ == "__main__":
    main()
